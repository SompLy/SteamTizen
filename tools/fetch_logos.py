"""Regenerate launcher/js/logos.js from the app catalogue's Simple Icons sources.

CC0 icon data; brands keep their trademarks.

  python3 tools/fetch_logos.py

Some brands were removed from newer Simple Icons releases, so catalogue entries
pin the source version for each logo.
"""

import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "launcher" / "js" / "app-catalog.js"
OUT = ROOT / "launcher" / "js" / "logos.js"


def logo_sources(catalog_path=CATALOG):
    """Read the data-only JS wrapper as JSON, without executing JavaScript."""
    source = catalog_path.read_text(encoding="utf-8")
    match = re.search(r"\bwindow\.AeroTizen\.catalog\s*=\s*(\{.*\})\s*;\s*\Z", source, re.DOTALL)
    if not match:
        raise ValueError(f"Expected a data-only catalogue in {catalog_path}")
    catalog = json.loads(match.group(1))
    sources = {}
    for app in catalog["apps"]:
        logo = app.get("fallback", {}).get("logo")
        if logo is None:
            continue
        if not isinstance(logo, dict):
            raise ValueError(f"Expected logo slug and version for {app['key']}")
        slug, version = logo.get("slug"), logo.get("version")
        if not isinstance(slug, str) or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
            raise ValueError(f"Invalid logo slug for {app['key']}")
        if not isinstance(version, str) or not re.fullmatch(r"(custom|\d+\.\d+\.\d+)", version):
            raise ValueError(f"Invalid logo version for {app['key']}")
        if slug in sources and sources[slug] != version:
            raise ValueError(f"Conflicting source versions for logo {slug}")
        sources[slug] = version
    return sources


def existing_logos(output_path=OUT):
    """Carry custom (non-CDN) logos and their viewBoxes across regenerations."""
    try:
        text = output_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return {}, {}
    match = re.search(r"window\.LOGOS = (\{.*?\});", text, re.DOTALL)
    logos = json.loads(match.group(1)) if match else {}
    boxes = re.search(r"window\.LOGO_BOXES = (\{.*\});", text, re.DOTALL)
    pairs = re.finditer(r"['\"]?([a-z0-9-]+)['\"]?\s*:\s*['\"]([^'\"]+)['\"]", boxes.group(1)) if boxes else iter(())
    return logos, {m.group(1): m.group(2) for m in pairs}


def generate(catalog_path=CATALOG, output_path=OUT):
    carried, carried_boxes = existing_logos(output_path)
    logos = {}
    for slug, ver in logo_sources(catalog_path).items():
        if ver == "custom":  # logos sourced elsewhere (official brand assets)
            if slug not in carried:
                raise ValueError(f"custom logo {slug} missing from {output_path}")
            logos[slug] = carried[slug]
            continue
        url = f"https://cdn.jsdelivr.net/npm/simple-icons@{ver}/icons/{slug}.svg"
        with urllib.request.urlopen(url, timeout=20) as response:
            svg = response.read().decode("utf-8")
        path = re.search(r'<path d="([^"]+)"', svg)
        if not path:
            raise ValueError(f"No SVG path found for {slug}@{ver}")
        logos[slug] = path.group(1)
        print(f"{slug:<14} {ver}")
    boxes = {slug: carried_boxes[slug] for slug in logos if slug in carried_boxes}
    with output_path.open("w", encoding="utf-8") as f:
        f.write("// Generated by tools/fetch_logos.py from Simple Icons (CC0); slugs with\n")
        f.write("// version \"custom\" come from official brand assets. Trademarks belong to their owners.\n")
        f.write("window.LOGOS = " + json.dumps(logos, indent=0) + ";\n")
        if boxes:
            f.write("window.LOGO_BOXES = " + json.dumps(boxes) + ";\n")
    print("wrote", output_path)


if __name__ == "__main__":
    generate()
